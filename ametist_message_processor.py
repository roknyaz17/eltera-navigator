"""
Процессор канала Аметист.

Аметист — это рабочий чат, а НЕ чистая лента вакансий. Особенности:
- Бо́льшая часть сообщений — переписка по конкретным кандидатам (СБ, такси,
  заселение, отказы, ЧС). Это шум, его нельзя отдавать LLM.
- Реальная потребность приходит нерегулярно (примерно раз в неделю) сообщением
  «📅 Обновляем потребность на текущую неделю … Прошу взять в работу» с
  нумерованным списком объектов (1. Ламода, 2. Кари, 3. Мираторг …).
- Иногда добавляют точечную потребность: «Дополнительная потребность ‼️ …».
- Бывает сообщение об ОТСУТСТВИИ потребности: «Сейчас на НУФ нет потребности».

Поэтому:
- Гейт сообщений жёсткий: пропускаем только те, где есть стем «потребност»
  (ловит «потребность» и «потребности»), и отбрасываем явные «нет потребност».
  Все кандидатские переписки так отсекаются.
- snapshot_marker = «Обновляем потребность» → недельный полный список считается
  снимком: всё, чего в нём нет (+ последующих «Дополнительная потребность»),
  деактивируется. «Дополнительная потребность» снимком НЕ считается — это апдейт.
- Сегментация по эмодзи невозможна (у каждой позиции свой эмодзи), поэтому
  отдаём сообщение LLM целиком (segment_emoji=None) — он вернёт массив вакансий.
- counterparty в тексте — это бренд-объект (Ламода/Кари/…), поэтому форсируем
  counterparty="Аметист", а бренд переезжает в object_name.
"""

from telegram_channel_processor import TelegramChannelProcessor


class AmetistMessageProcessor(TelegramChannelProcessor):
    SOURCE_NAME = "Аметист"
    SOURCE_URL_FALLBACK = "https://t.me/c/3512694527"
    SNAPSHOT_MARKER = "Обновляем потребность"
    COUNTERPARTY = "Аметист"

    def __init__(self, sheets_service, llm_parser):
        super().__init__(
            sheets_service,
            llm_parser,
            source_name=self.SOURCE_NAME,
            source_url_fallback=self.SOURCE_URL_FALLBACK,
            snapshot_marker=self.SNAPSHOT_MARKER,
            segment_emoji=None,            # не режем по эмодзи, отдаём всё сообщение LLM
            counterparty_override=self.COUNTERPARTY,
        )

    def _has_vacancy_signals(self, text: str) -> bool:
        """Аметист — рабочий чат. Пропускаем ТОЛЬКО сообщения о потребности.

        Переопределяем базовый детектор: общий словарь ключевых слов здесь не
        годится (он пропустил бы переписку по кандидатам со словами «смена»,
        «ставка», «грузчик» и т.п.). Единственный надёжный сигнал — слово
        «потребность», при этом явный отказ «нет потребности» отбрасываем.
        """
        if not text:
            return False
        low = text.lower()
        if "потребност" not in low:
            return False
        if "нет потребност" in low:  # «Сейчас на НУФ нет потребности»
            return False
        return True
