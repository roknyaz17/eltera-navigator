#!/bin/sh
# Постоянный контроль выкатки HTTPS: четыре пробы, ни одна из которых не
# расходует попытки входа и не требует пароля.
#
# Зачем это отдельный скрипт, а не строчка в регламенте: после выкатки
# ломаются ТИХО ровно три вещи, и ни одна не видна в логах приложения.
#   1. Сертификат перестал продлеваться. Письма не будет: Let's Encrypt
#      прекратил рассылку предупреждений об истечении 4 июня 2025 года.
#      Действующий сертификат ещё месяц выглядит здоровым, а потом сайт
#      закрывается для всех сразу.
#   2. Приложение перестало понимать заголовки прокси (пропала строка
#      FORWARDED_ALLOW_IPS, пересобрали образ, сузили доверие до адреса
#      контейнера). Страницы открываются, а любой POST отвечает 403 —
#      «сайт работает, но кнопки не нажимаются».
#   3. Исчез сам прокси: из .env пропала строка COMPOSE_PROFILES=tls и
#      очередной `docker compose up -d --remove-orphans` снёс контейнер.
#
# ГДЕ ЗАПУСКАТЬ. На сервере — можно, но этого мало: у мёртвого сервера cron
# молчит, и молчание неотличимо от «всё хорошо». Основной запуск — снаружи,
# на машине администратора или в системе мониторинга заказчика, по расписанию,
# с оповещением по ненулевому коду возврата.
#
#   0 9 * * *  /opt/eltera-bot/scripts/tls_watch.sh nav.example.ru >/dev/null
#
# Стандартный вывод — построчный отчёт (в cron его глушат), стандартный поток
# ошибок — только строки «ТРЕВОГА». Код возврата: 0 — всё хорошо, 1 — есть
# сработавшая проба, 2 — неверный вызов.
#
# Зависимости: curl и openssl. Разбора дат нет намеренно: `openssl x509
# -checkend` считает срок сам и одинаково работает на любой системе.

set -u

D="${1:-${NAVIGATOR_DOMAIN:-}}"
DAYS="${2:-20}"

if [ -z "$D" ]; then
	echo "вызов: $0 <домен> [дней-до-тревоги]" >&2
	exit 2
fi

FAILED=0

alarm() {
	echo "ТРЕВОГА: $1" >&2
	FAILED=1
}

# Код ответа. Соединения не было вовсе — curl сам печатает 000 и выходит
# с ошибкой; подставлять 000 ещё раз нельзя, получится «000000».
code() {
	out="$(curl -sS -o /dev/null -m 10 -w '%{http_code}' "$@" 2>/dev/null)"
	if [ -n "$out" ]; then printf '%s' "$out"; else printf '000'; fi
}

check() {
	# check <что проверяем> <ожидаемый код> <фактический код>
	if [ "$2" = "$3" ]; then
		printf '  ok     %s: %s\n' "$1" "$3"
	else
		printf '  ОТКАЗ  %s: %s (ждали %s)\n' "$1" "$3" "$2"
		alarm "$1: $3, ждали $2"
	fi
}

echo "проба $D, $(date '+%F %T')"

# 1. Сайт вообще отвечает по https. /health открыт без авторизации
#    (app.py:608) и отдаёт ровно {"status":"ok"} — ничего лишнего наружу.
check 'https, /health' 200 "$(code "https://$D/health")"

# 2. Порт 80 занят нашей Caddy и отвечает редиректом. Если здесь не 308 —
#    на 80 кто-то другой, и продление сертификата уже сломано, хотя
#    действующий сертификат ещё месяц будет валиден.
check 'http -> https, редирект' 308 "$(code "http://$D/health")"

# 3. Вход работает. POST /logout сверяет Origin (app.py:565), но не требует
#    авторизации и НЕ расходует попытки входа — единственная безопасная
#    проба формы. 403 здесь означает, что uvicorn перестал доверять
#    заголовкам прокси: схема в base_url снова http, и ни вход, ни смена
#    пароля, ни правка пользователей больше не работают.
check 'вход жив (POST /logout)' 303 \
	"$(code -X POST -H "Origin: https://$D" "https://$D/logout")"

# 4. Срок сертификата. Caddy продлевает примерно за 30 дней до конца, то есть
#    на 60-й день из 90. Тревога за 20 дней — уже после того, как продление
#    должно было пройти и не прошло; напоминание за 30 дней стояло бы ровно
#    на границе окна продления и срабатывало бы вхолостую каждые три месяца.
CERT="$(echo | openssl s_client -connect "$D:443" -servername "$D" 2>/dev/null)"
if printf '%s' "$CERT" | grep -q 'BEGIN CERTIFICATE'; then
	ENDS="$(printf '%s' "$CERT" | openssl x509 -noout -enddate 2>/dev/null | cut -d= -f2)"
	if printf '%s' "$CERT" | openssl x509 -noout -checkend $((DAYS * 86400)) >/dev/null 2>&1; then
		printf '  ok     срок сертификата: %s\n' "$ENDS"
	else
		printf '  ОТКАЗ  срок сертификата: %s\n' "$ENDS"
		alarm "сертификат истекает меньше чем через $DAYS дней: $ENDS"
	fi
else
	printf '  ОТКАЗ  срок сертификата: сертификат не получен\n'
	alarm "не удалось забрать сертификат с $D:443"
fi

exit $FAILED
