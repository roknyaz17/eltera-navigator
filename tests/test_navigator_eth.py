"""Разбор ограничений по национальности в заявках.

Все формулировки ниже — дословно из реестра (874 позиции, срез на 26.08.2026),
а не придуманы. Заказчики пишут это в «Требованиях» и «Рисках» десятком разных
способов, и цена ошибки несимметрична: сказать «можно» там, где запрет, значит
отправить человека на объект, где ему откажут на проходной.
"""

from navigator_api import parse_ethnic_limits


def st(*sources):
    limits = parse_ethnic_limits(*sources)
    return limits["kav"]["st"], limits["gyp"]["st"]


# ------------------------------------------------------------------ молчание

def test_пустая_заявка_ничего_не_утверждает():
    assert st("") == ("na", "na")
    assert st(None, None) == ("na", "na")


def test_молчание_не_значит_разрешено():
    """Две трети позиций про это не пишут — и это «не сказано», а не «можно»."""
    assert st("до 50 лет, только РФ, минимальный опыт за конвейером") == ("na", "na")


def test_упоминание_без_полярности_не_запрет():
    """«Озон ЛЦ Кавказский» — это объект, а не ограничение."""
    assert st("опыт работы на складе Озон ЛЦ Кавказский") == ("na", "na")


# --------------------------------------------------------------------- запрет

def test_строго_не():
    assert st("до 50 лет, строго не Кавказ, СТРОГО НЕ ЦЫГАН, только РФ") == ("ban", "ban")


def test_запрет_после_перечисления():
    """Запрет стоит справа от списка — относится к обоим пунктам."""
    assert st("РФ/РБ, возраст от 18 до 60, Кавказ и Цыгане запрет") == ("ban", "ban")
    assert st("Красные - можно согласовать. Кавказ, Цыгане запрет на трудоустройство") == ("ban", "ban")


def test_запрет_перед_перечислением():
    """А здесь слева, и «цыган» своего маркера не несёт."""
    assert st("запрет на трудоустройство кавказцев, цыган, пенсионеров") == ("ban", "ban")


def test_под_запретом_и_национальность():
    assert st("Без судимостей! От 18 до 45. Кавказ под запретом")[0] == "ban"
    assert st("граждане РФ и ЕАЭС, запрет на кандидатов кавказской национальности")[0] == "ban"


def test_запрет_из_поля_рисков():
    """Сигнал живёт не только в «Требованиях»: 23 позиции держат его в «Рисках»."""
    assert st("Граждане РФ и ЕАЭС", "РФ / ЕАЭС", "Кавказ и Цыгане запрет") == ("ban", "ban")


def test_славянская_внешность_это_тот_же_запрет():
    """Отдельный способ сказать то же самое — две позиции пишут только так."""
    kav, gyp = st("славянская внешность, РФ, от 30 до 50 лет, физически крепкие")
    assert (kav, gyp) == ("ban", "ban")


def test_славянская_внешность_не_перебивает_явное_разрешение():
    limits = parse_ethnic_limits("строго славянская внешность и ФИО, Кавказ можно")
    assert limits["kav"]["st"] == "ok"
    assert limits["gyp"]["st"] == "ban"


# ----------------------------------------------------------------- разрешение

def test_кавказ_можно_а_цыгане_нет():
    """Полярность привязана к своему пункту, а не ко всей строке."""
    assert st("РФ (Кавказ МОЖНО, Цыгане запрет), М 18-55 / Ж 18-50") == ("ok", "ban")
    assert st("РФ, Кавказ можно, цыгане запрет, возраст М 18-55") == ("ok", "ban")


def test_по_согласованию_это_разрешение_с_оговоркой():
    assert st("РФ/РБ (Кавказ по согласованию), от 18-55")[0] == "ok"


def test_фотосогласование_не_является_разрешением():
    """«свыше фотосогласование» стоит рядом сплошь и полярности не несёт."""
    assert st("до 50 лет, строго не Кавказ, свыше фотосогласование, только РФ")[0] == "ban"


def test_допускаются_правонарушения_не_является_разрешением():
    kav, _ = st(
        "граждане РФ и ЕАЭС, запрет на кандидатов кавказской национальности, "
        "допускаются административные правонарушения, долг до 100000 руб."
    )
    assert kav == "ban"


# ------------------------------------------------------ «можно только женщин»

def test_женщинам_можно():
    assert st("до 50 лет, РФ / РБ, ж можно Кавказ")[0] == "women"
    assert st("до 45 лет, только РФ, женщинам можно Кавказ")[0] == "women"


def test_запрет_только_мужчинам_это_то_же_самое():
    """«запрет на кавказцев (мужчин)» и «ж можно Кавказ» — одно и то же."""
    limits = parse_ethnic_limits(
        "Граждане РФ и ЕАЭС, строго без уголовной судимости, "
        "запрет на кавказцев (мужчин), цыган, пенсионеров"
    )
    assert limits["kav"]["st"] == "women"
    # Цыган оговорка про пол не касается: у них запрет полный.
    assert limits["gyp"]["st"] == "ban"


def test_оговорка_про_пол_попадает_в_подпись():
    """Иначе «Запрет: кавказцы» рядом с «можно женщин» читается как ошибка."""
    note = parse_ethnic_limits("Запрет на трудоустройство: кавказцы (мужчины), цыгане")["kav"]["note"]
    assert "мужчин" in note


# ------------------------------------------------------------ спорные случаи

def test_расхождение_источников_читается_как_запрет():
    """Позиция ELT-2026-000266-01: «Требования» говорят одно, «Риски» — другое."""
    limits = parse_ethnic_limits(
        "РФ, Кавказ можно, цыгане запрет, возраст М 18-55", "РФ", "Кавказ и Цыгане запрет",
    )
    assert limits["kav"]["st"] == "ban"
    # Оба куска остаются в подписи: рекрутёр должен видеть расхождение сам.
    assert "можно" in limits["kav"]["note"] and "запрет" in limits["kav"]["note"]


def test_подпись_не_двоится():
    """Одна и та же фраза лежит и в «Требованиях», и в «Гражданстве»."""
    note = parse_ethnic_limits(
        "РФ/РБ (Кавказ по согласованию), от 18-55", "РФ/РБ (Кавказ по согласованию)",
    )["kav"]["note"]
    assert note.lower().count("по согласовани") == 1


def test_подпись_цитирует_дословно_и_с_регистром():
    note = parse_ethnic_limits("до 50 лет, СТРОГО НЕ ЦЫГАН, только РФ")["gyp"]["note"]
    assert note == "СТРОГО НЕ ЦЫГАН"
