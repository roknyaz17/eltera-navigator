"""Выбор по областям: сведение написаний и список областей для панели.

Суть требования — «покажи всё, что есть в Тульской области» должно показывать
именно всё. Ломается это двумя способами: одна область распадается на два
написания («Мордовия» и «Республика мордовия») или позиция без города вообще
никуда не попадает. Оба случая здесь и проверяются — на тех написаниях, которые
реально лежат в реестре.
"""

import pytest

import navigator_api
from registry import geo


# ------------------------------------------------------- написание области

@pytest.mark.parametrize("raw,expected", [
    ("Тульская область", "Тульская область"),
    ("тульская обл.", "Тульская область"),
    ("ТУЛЬСКАЯ ОБЛАСТЬ", "Тульская область"),
    # Такой области не существует: Саранск — столица Мордовии.
    ("САРАНСКАЯ область", "Республика Мордовия"),
    ("Мордовия", "Республика Мордовия"),
    ("Республика мордовия", "Республика Мордовия"),
    ("Республика татарстан", "Республика Татарстан"),
    ("Татарстан", "Республика Татарстан"),
    ("Республика саха (якутия)", "Республика Саха (Якутия)"),
    # Город в графе региона.
    ("Екатеринбург", "Свердловская область"),
    ("Москва", "Москва и область"),
    ("Москва и МО", "Москва и область"),
    ("Московская область", "Москва и область"),
    ("Санкт-Петербург", "Санкт-Петербург и область"),
    ("Ленинградская область", "Санкт-Петербург и область"),
    ("", ""),
    (None, ""),
])
def test_region_title(raw, expected):
    assert geo.region_title(raw) == expected


def test_unknown_region_keeps_its_words():
    """Незнакомое название не приклеивается к похожему — правится регистр."""
    assert geo.region_title("волгоградская область") == "Волгоградская область"
    assert geo.region_title("ЯНАО") == "ЯНАО"


def test_region_from_city_only_from_dictionary():
    """Регион не написан — берём из справочника «город → регион». Города в
    справочнике нет — регион остаётся пустым, а не подставляется соседний."""
    dictionary = {"балашиха": "Московская область", "венев": "Тульская область"}
    assert geo.resolve_region("", "Балашиха", dictionary) == "Москва и область"
    assert geo.resolve_region(None, "Венев", dictionary) == "Тульская область"
    assert geo.resolve_region("", "Урюпинск", dictionary) == ""
    assert geo.resolve_region("", "Балашиха", None) == ""


def test_source_region_wins_over_dictionary():
    """Что написал источник, то и регион: справочник только заполняет пустое."""
    dictionary = {"венев": "Московская область"}
    assert geo.resolve_region("Тульская область", "Венев", dictionary) == "Тульская область"


# --------------------------------------------------------- список областей

def row(region, city="", position_id="P-1"):
    return {"id": position_id, "region": region, "city": city}


def test_regions_block_counts_positions_and_cities():
    block = navigator_api.regions_block([
        row("Тульская область", "Венев"),
        row("Тульская область", "Венев"),
        row("Тульская область", ""),          # города нет — позиция всё равно в области
        row("Москва и область", "Балашиха"),
    ])
    assert [(x["name"], x["count"], x["cities"]) for x in block] == [
        ("Тульская область", 3, 1),
        ("Москва и область", 1, 1),
    ]


def test_regions_block_keeps_positions_without_region_last():
    """«Регион не указан» — отдельная строка выбора, а не потерянные позиции."""
    block = navigator_api.regions_block([
        row("", ""),
        row("Тульская область", "Венев"),
        row("", ""),
    ])
    assert [x["name"] for x in block] == ["Тульская область", ""]
    assert block[-1]["count"] == 2


def test_regions_block_covers_every_position():
    rows = [row("Тульская область", "Венев"), row("", ""), row("Москва и область", "Химки")]
    assert sum(x["count"] for x in navigator_api.regions_block(rows)) == len(rows)


# ------------------------------------------------- подпись места в карточке

@pytest.mark.parametrize("region,city,same", [
    ("Москва и область", "Москва", True),
    ("Санкт-Петербург и область", "Санкт-Петербург", True),
    ("Москва и область", "Балашиха", False),
    ("Тульская область", "", False),
])
def test_same_place(region, city, same):
    """«Москва · Москва и область» в карточке читалось бы как ошибка."""
    assert navigator_api._same_place(region, city) is same
