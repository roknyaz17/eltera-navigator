"""Приёмник листа Табии.

Фикстуры списаны с настоящего листа: капс в названиях, многострочные ячейки,
сноски в скобках, объекты в нулях, два одноимённых «Стройка ЖК» и врезка с
адресом офиса. Разбор самих вакансий здесь не проверяется — его делает модель,
приёмник только отдаёт ей строку (см. докстринг tabiya_sheet_extractor).
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from registry.dictionaries import norm_key  # noqa: E402
from tabiya_sheet_extractor import TabiyaSheetExtractor  # noqa: E402

ШАПКА = [" ", "ОБЪЕКТ", "ВАКАНСИИ И ПОТРЕБНОСТЬ", "ТАРИФНАЯ СТАВКА\r", "КОГО ИЩЕМ",
         "ПИТАНИЕ\r", "Проверка СБ", "КОЛ-ВО СМЕН", "ОБЯЗАННОСТИ",
         "УСЛОВИЯ ПРОЖИВАНИЯ\r", "ГРАФИК РАБОТЫ\r", "СПЕЦОДЕЖДА",
         "МЕДИЦИНСКАЯ КНИЖКА", "Адрес проживания", "Адрес работы"]

КОНСЕРВЫ = ["1", "КОНСЕРВЫ\nМО, г. Мытищи",
            "Грузчик - 4 М срочно\nУпаковщица - 0 Ж\n(с готовой мед книжкой)",
            "1я смена не оплачивается (9 часов)\nГрузчик/упаковщица:\n3 600 руб смена\n"
            "ВОДИТЕЛЬ: 4 500 руб.",
            "Гражданство: РФ, СНГ\nВозраст: 18-50", "Комната приема пищи", "Нет", "33/45",
            "Упаковка, стикеровка", "Квартира", "График вахта 6/1\nСмены день и ночь",
            "В своей", "Помогаем оформить", "", ""]

НУЛИ = ["20", "ХЛОПЬЯ\n(производство зерновых хлопьев)\nМО, г. Люберцы",
        "Разнорабочий - 0", "3 600 руб смена", "Гражданство: РФ", "Есть", "Да",
        "20/33/45", "Фасовка", "Общежитие", "График 6/1", "Выдаём", "Нет", "", ""]

ВРЕЗКА = ["Запись в офис: https://forms.gle/xxxx", "",
          "АДРЕС ОФИСА:\nЖдём Вас на оформление", "", "", "", "", "", "", "", "", "", "", "", ""]

СТРОЙКА_МЫТИЩИ = ["12", "Стройка ЖК\nг. Мытищи", "Разнорабочий - 3 М", "4 100 руб",
                  "Только РФ / РБ", "Комната", "Без тяжких", "33/45", "Работа с болгаркой",
                  "Общежитие", "График 6/1", "Форма", "Нет", "", ""]
СТРОЙКА_МОСКВА = ["13", "Стройка ЖК\nм. Озерная\nг. Москва", "Разнорабочий - 0", "4 100 руб",
                  "Только РФ / РБ", "Комната", "Без тяжких", "33/45", "Работа с болгаркой",
                  "Общежитие", "График 6/1", "Форма", "Нет", "", ""]


def собрать(*строки):
    return TabiyaSheetExtractor(sheets_service=None).build_requests([ШАПКА, *строки])


# ------------------------------------------------------- что становится заявкой

def test_строка_с_объектом_становится_заявкой():
    заявки = собрать(КОНСЕРВЫ)
    assert len(заявки) == 1
    assert заявки[0].source == "tabiya"
    assert заявки[0].source_name == "Табия"


def test_врезка_с_адресом_офиса_заявкой_не_становится():
    """У неё пустая ячейка «ОБЪЕКТ» — по этому признаку и отсеиваем."""
    заявки = собрать(КОНСЕРВЫ, ВРЕЗКА, НУЛИ)
    assert len(заявки) == 2
    assert all("АДРЕС ОФИСА" not in з.raw_text for з in заявки)


def test_строка_без_номера_не_теряется():
    """Номера в листе идут с пропусками и иногда отсутствуют — это не признак
    служебной строки, и потерять из-за него объект нельзя."""
    без_номера = ["", *КОНСЕРВЫ[1:]]
    assert len(собрать(без_номера)) == 1


def test_объект_со_всеми_нулями_попадает_в_реестр():
    """19 объектов из 27 стоят в нулях — это живой каталог без набора."""
    заявки = собрать(НУЛИ)
    assert len(заявки) == 1
    assert "Разнорабочий - 0" in заявки[0].raw_text


def test_ссылка_внутри_строки_объекта_не_делает_её_служебной():
    со_ссылкой = list(КОНСЕРВЫ)
    со_ссылкой[1] = "КОНСЕРВЫ\nг. Мытищи\nhttps://yandex.ru/maps/org/123"
    assert len(собрать(со_ссылкой)) == 1


# ------------------------------------------------------------ что форсим

def test_объект_форсится_первой_строкой_ячейки():
    з = собрать(КОНСЕРВЫ)[0]
    assert з.field_overrides["object_name"] == "КОНСЕРВЫ"
    assert з.field_overrides["counterparty"] == "Табия"


def test_город_не_форсится():
    """Город записан по-разному и разбирается моделью: регулярка на этом листе
    выдавала «СРОЧНО» и «ПРОИЗВОДСТВО», потому что он написан капсом."""
    з = собрать(КОНСЕРВЫ)[0]
    assert "city" not in з.field_overrides
    assert "МО, г. Мытищи" in з.raw_text


def test_уточнение_в_скобках_не_попадает_в_название_объекта():
    з = собрать(НУЛИ)[0]
    assert з.field_overrides["object_name"] == "ХЛОПЬЯ"


# ------------------------------------------------------------- текст модели

def test_переносы_строк_в_ячейках_сохраняются():
    """В «ТАРИФНОЙ СТАВКЕ» одна строка про грузчика, другая про водителя:
    схлопывание в пробел путает модель, кому какая ставка."""
    текст = собрать(КОНСЕРВЫ)[0].raw_text
    assert "Грузчик/упаковщица:\n3 600 руб смена" in текст
    assert "ВОДИТЕЛЬ: 4 500 руб." in текст


def test_подписи_колонок_очищены_от_возврата_каретки():
    текст = собрать(КОНСЕРВЫ)[0].raw_text
    assert "ТАРИФНАЯ СТАВКА:" in текст
    assert "\r" not in текст


def test_в_тексте_есть_оговорка_про_день_и_ночь():
    """shift_type входит в ключ позиции: без оговорки модель вернёт две
    вакансии вместо одной и поделит между ними потребность."""
    текст = собрать(КОНСЕРВЫ)[0].raw_text
    assert "ОДНА вакансия" in текст and "Не дели" in текст


def test_в_тексте_есть_оговорка_про_ноль():
    текст = собрать(НУЛИ)[0].raw_text
    assert "0 означает" in текст and "потребность у неё 0" in текст


def test_сноски_в_скобках_объявлены_пояснением():
    текст = собрать(КОНСЕРВЫ)[0].raw_text
    assert "Строки в скобках" in текст


# ------------------------------------------------------------- ключ заявки

def test_ключ_заявки_переживает_перестановку_строк():
    прямо = [з.source_ref for з in собрать(КОНСЕРВЫ, НУЛИ)]
    обратно = [з.source_ref for з in собрать(НУЛИ, КОНСЕРВЫ)]
    assert set(прямо) == set(обратно)
    assert len(set(прямо)) == 2


def test_одноимённые_объекты_получают_разные_ключи():
    """Два «Стройка ЖК» различаются номером объекта, а не порядком строк."""
    заявки = собрать(СТРОЙКА_МЫТИЩИ, СТРОЙКА_МОСКВА)
    ключи = [з.source_ref for з in заявки]
    assert len(set(ключи)) == 2
    assert all("#" not in к for к in ключи)


def test_разделитель_ключа_переживает_нормализацию():
    """norm_key съедает «|», поэтому разделителем взят «/»."""
    assert norm_key("12/Стройка ЖК") != norm_key("13/Стройка ЖК")


# --------------------------------------------------------- отказ по-громкому

def test_узкий_лист_не_отдаёт_заявок():
    узкий = TabiyaSheetExtractor(sheets_service=None).build_requests(
        [[" ", "ОБЪЕКТ"], ["1", "КОНСЕРВЫ"]]
    )
    assert узкий == []


def test_пустой_лист_не_отдаёт_заявок():
    assert TabiyaSheetExtractor(sheets_service=None).build_requests([]) == []
    assert TabiyaSheetExtractor(sheets_service=None).build_requests([ШАПКА]) == []


def test_лист_шире_шапки_не_теряет_колонки():
    широкая = [*КОНСЕРВЫ, "лишняя колонка"]
    текст = собрать(широкая)[0].raw_text
    assert "лишняя колонка" in текст
