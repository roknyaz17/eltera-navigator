"""Оформление и поле «%» в карточке позиции.

Формулировки дословно из реестра (срезы 16.09 и 15.10.2026). «%» говорит
рекрутёру, как читать ставку самозанятого: «+6%» — налог платит контрагент,
«−6%» — платит сам человек (так же, если в заявке не сказано), «ТК»/«ГПХ» —
оформление не самозанятое.
"""

from navigator_api import hire_forms, tax_block


def row(source="vahtapro", raw="", kb="", **fields):
    out = {"source": source, "raw_text": raw, "kb_text": kb}
    out.update(fields)
    return out


# ------------------------------------------------------------------ Табия

def test_табия_всегда_тк():
    """Руководитель: все вакансии Табии — по ТК, что бы ни стояло в таблице."""
    r = row("tabiya", raw="ТАРИФНАЯ СТАВКА:\n290 руб/час - СЗ / 260 руб/час - ТК")
    assert hire_forms(r) == ["ТК"]
    assert tax_block(r)["v"] == "ТК"


def test_табия_без_слова_об_оформлении_тоже_тк():
    r = row("tabiya", raw="МЕДИЦИНСКАЯ КНИЖКА: Помогаем оформить с вычетом из ЗП до 3500р")
    assert hire_forms(r) == ["ТК"]
    assert tax_block(r) == {"v": "ТК", "st": "yes", "who": "", "note": ""}


# -------------------------------------------------------------------- КНК

def test_кнк_налог_платит_сотрудник():
    r = row("kpk", transport_terms=(
        "Налог самозанятого оплачивается сотрудником самостоятельно (4-6%). "
        "Транспортные расходы вычитаются, если кандидат не отработает 3 смены."))
    t = tax_block(r)
    assert hire_forms(r) == ["СЗ"]
    assert (t["v"], t["st"], t["who"]) == ("−6%", "yes", "worker")
    assert t["note"] == "Налог самозанятого оплачивается сотрудником самостоятельно (4-6%)"


def test_кнк_ставка_налога_без_плательщика_значит_сам():
    t = tax_block(row("kpk", transport_terms="Проезд оплачивается сотрудником самостоятельно. Ставка налога 4-6%"))
    assert (t["v"], t["who"], t["note"]) == ("−6%", "worker", "Ставка налога 4-6%")


def test_самозанятое_третье_лицо_не_оформление_кандидата():
    """«3-е лицо должно быть САМОЗАНЯТЫМ» — условие выплаты, не форма найма."""
    r = row("kpk", raw="Получение ЗП на 3-е лицо: Оформление по ТК РФ\n"
                       "Получение ЗП на 3-е лицо: 3-е лицо должно быть совершеннолетним и САМОЗАНЯТЫМ")
    assert hire_forms(r) == ["ТК"]
    assert tax_block(r)["v"] == "ТК"


def test_кнк_без_формы_в_заявке_самозанятые():
    r = row("kpk", raw="Получение ЗП на 3-е лицо: 3-е лицо должно быть совершеннолетним и САМОЗАНЯТЫМ")
    assert hire_forms(r) == ["СЗ"]
    assert tax_block(r) == {"v": "−6%", "st": "def", "who": "", "note": ""}


def test_сокращение_смз_рядом_с_третьим_лицом_остаётся_оформлением():
    """Аметист: «выплаты по СМЗ — на себя или на третье лицо» — это и есть СЗ."""
    r = row("ametist", raw="💰 Выплаты: производятся по СМЗ — можно оформить на себя или "
                           "на третье лицо через платформу «Консоль».")
    assert hire_forms(r) == ["СЗ"]


# ----------------------------------------------------------------- Градус

def test_налог_компенсируется_плюс_шесть():
    t = tax_block(row(risks="Оформление по СМЗ, налог 6% компенсируется. Расчёт по окончании вахты."))
    assert (t["v"], t["st"], t["who"]) == ("+6%", "yes", "employer")
    assert t["note"] == "Оформление по СМЗ, налог 6% компенсируется"


def test_налог_за_счёт_компании_плюс_шесть():
    t = tax_block(row(kb="Оформление: Оформление по СЗ, оплата налога за счет компании!"))
    assert (t["v"], t["who"]) == ("+6%", "employer")


def test_ставка_плюс_шесть_процентов():
    t = tax_block(row(kb="Оформление только тк, возможно оформление по смз\nСМЗ = 3960 + 6%"))
    assert (t["v"], t["who"]) == ("ТК / +6%", "employer")


def test_диапазон_выработки_не_налог():
    """«СПК (60%-80%)» — процент выработки, а не минус налог."""
    t = tax_block(row(raw="✅Оформление по СМЗ\nСПК (60%-80%) - 415р/час (4565р/смена)"))
    assert (t["v"], t["st"]) == ("−6%", "def")


def test_компенсация_проезда_рядом_не_про_налог():
    t = tax_block(row(raw="Оформление СМЗ, налог 6%, компенсация проезда до 2000"))
    assert t["who"] == "worker"


def test_пост_главнее_карточки_объекта():
    """Градус перевёл проекты на ТК, а описание на диске ещё про СМЗ."""
    r = row(raw="❗️Внимание, на всех проектах оформление ПО ТК ❗️",
            kb="Оформление по СМЗ, налог 6% компенсируется.")
    assert hire_forms(r) == ["ТК"]
    assert tax_block(r)["v"] == "ТК"


def test_карточка_объекта_заполняет_молчание_поста():
    r = row(raw="👉Грузчик/3498 руб/смена - 10 м",
            kb="Оформление по СМЗ, налог 6% компенсируется.")
    assert hire_forms(r) == ["СЗ"]
    assert tax_block(r)["v"] == "+6%"


# ------------------------------------------------------- прочие и смешанные

def test_тк_без_процента():
    t = tax_block(row("yappi", raw="ОФОРМЛЕНИЕ: ТК\nЗАРПЛАТА: 6200 рублей/cмена"))
    assert t == {"v": "ТК", "st": "yes", "who": "", "note": ""}


def test_несколько_форм_несколько_вариантов():
    t = tax_block(row("melior", raw="📑 Оформление ТК, СЗ, обязательно наличие регистрации"))
    assert (t["v"], t["st"]) == ("ТК / −6%", "def")
    assert tax_block(row("melior", raw="📑 Оформление ГПХ"))["v"] == "ГПХ"


def test_ничего_не_сказано_минус_шесть_по_умолчанию():
    t = tax_block(row("marketstaff", raw="Зарплата за смену: 4000 руб. ( сделка 100%)"))
    assert t == {"v": "−6%", "st": "def", "who": "", "note": ""}


def test_платит_сам_сильнее_компенсации():
    """Противоречие в одной заявке решаем в сторону меньших денег."""
    t = tax_block(row(raw="Налог компенсируется. Налог самозанятого оплачивается сотрудником самостоятельно"))
    assert t["who"] == "worker"
