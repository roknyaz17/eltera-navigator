_PREFIX_RE = re.compile(r"^\s*(?:г\.?|город|пос\.?|посёлок|поселок|с\.?|село|д\.?|деревня|мкр\.?)\s+?", re.IGNORECASE)
_TAIL_RE = re.compile(r"[\s,]+(?:мо|м\.о\.?|московская\s+обл\.?(?:асть)?)\s*$", re.IGNORECASE)


def _titlecase(value: str) -> str:
    """«набережные челны» → «Набережные Челны», дефисы тоже слова."""
    parts = re.split(r"([\s\-])", value)
    out = []
    for part in parts:
        if not part or part in (" ", "-"):
            out.append(part)
            continue
        out.append(part[0].upper() + part[1:])
    return "".join(out)


def normalize_city(raw: Optional[str]) -> str:
    """Написание города из источника → единое название для интерфейса.

    Пустое остаётся пустым: «город не указан» — это состояние данных, а не
    повод подставить регион.
    """
    if not raw:
        return ""
    value = " ".join(str(raw).split()).strip(" ,.;")
    if not value:
        return ""
    key = value.lower().replace("ё", "е")
    if key in CITY_ALIASES:
        return CITY_ALIASES[key]
    value = _TAIL_RE.sub("", value)
    value = _PREFIX_RE.sub("", value)
    value = value.strip(" ,.;")
    key = value.lower().replace("ё", "е")
    if key in CITY_ALIASES:
        return CITY_ALIASES[key]
    return _titlecase(value)


def normalize_region(raw: Optional[str]) -> str:
    """Регион показываем так, как его написал источник, — правим только регистр
    первой буквы. «Московская Область» вместо «Московская область» читается как
    ошибка, а угадывать, где в «Москва и МО» настоящая аббревиатура, незачем."""
    if not raw:
        return ""
    value = " ".join(str(raw).split()).strip(" ,.;")
    if not value:
        return ""
    return value[0].upper() + value[1:]


def coords(city: str) -> Optional[Tuple[float, float]]:
    """Координаты нормализованного города или None, если города нет в справочнике."""
    if not city:
        return None
    return CITY_COORDS.get(city)
