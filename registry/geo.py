# Родовые слова названия: внутри строки остаются строчными («Тульская
# область», а не «Тульская Область»).
_REGION_GENERIC = {"область", "край", "округ", "республика", "автономный", "район", "и"}

# Сокращения, которые встречаются в заявках наравне с полным словом.
_REGION_ABBR = {"обл": "область", "респ": "республика"}


def _region_key(value: str) -> str:
    """Ключ для сравнения написаний: регистр, ё/е, точки и сокращения не в счёт."""
    text = str(value).lower().replace("ё", "е")
    text = re.sub(r"[^\w\s-]", " ", text, flags=re.UNICODE)
    return " ".join(_REGION_ABBR.get(word, word) for word in text.split())


def _region_word(word: str, first: bool) -> str:
    core = re.sub(r"[\W\d_]", "", word, flags=re.UNICODE).lower().replace("ё", "е")
    # ХМАО, ЯНАО, МО — аббревиатуры, а не «Хмао»: регистр не трогаем.
    if word.isupper() and 2 <= len(core) <= 4 and core not in _REGION_ABBR:
        return word
    # «обл.» и «область» должны выглядеть одинаково, иначе в списке появятся
    # две строки на одну область.
    lowered = _REGION_ABBR.get(core, word.lower().strip(" ."))
    if not first and lowered in _REGION_GENERIC:
        return lowered
    return re.sub(r"[^\W\d_]", lambda m: m.group(0).upper(), lowered, count=1)


def region_title(raw: Optional[str]) -> str:
    """Написание региона из источника → единое название для выбора по областям.

    Незнакомое название не выбрасывается и ни к чему не приклеивается — ему
    правится только регистр («САРАНСКАЯ область» → «Саранская область»).
    Склеиваются лишь те написания, которые перечислены в REGION_ALIASES.
    """
    if not raw:
        return ""
    value = " ".join(str(raw).split()).strip(" ,.;")
    if not value:
        return ""
    alias = REGION_ALIASES.get(_region_key(value))
    if alias:
        return alias
    return " ".join(_region_word(word, index == 0) for index, word in enumerate(value.split()))


def resolve_region(
        raw: Optional[str],
        city: str = "",
        city_regions: Optional[Dict[str, str]] = None,
) -> str:
    """Регион позиции: что написал источник, а если не написал — по городу.

    Город → регион берётся из подтверждённого человеком справочника
    `city_region` — того же, которым пользуется приём (registry/normalize.py).
    Города в справочнике нет — регион остаётся пустым: догадываться по адресу
    или ставить позицию в соседнюю область мы не будем.
    """
    title = region_title(raw)
    if title:
        return title
    if city and city_regions:
        return region_title(city_regions.get(norm_key(city), ""))
    return ""


def coords(city: str) -> Optional[Tuple[float, float]]:
    """Координаты нормализованного города или None, если города нет в справочнике."""
    if not city:
        return None
    return CITY_COORDS.get(city)
